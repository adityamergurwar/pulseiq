"""Validate the Phase 4 release surfaces and write concise evidence."""
from __future__ import annotations

from datetime import date
import os
from pathlib import Path
import re
import sys

import duckdb

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from pulseiq.api import API_METRICS, get_metric, list_metrics
from scripts.build_monthly_pack import build as build_pdf
from scripts.build_monthly_excel import build as build_excel


DB = Path(os.environ.get("PULSEIQ_DB_PATH", ROOT / "pulseiq.duckdb"))
OUTPUT = ROOT / "docs" / "phase4_validation.md"


def run() -> list[tuple[str, bool, str]]:
    checks: list[tuple[str, bool, str]] = []
    with duckdb.connect(str(DB), read_only=True) as con:
        cutoff, refresh, status = con.execute(
            "SELECT data_cutoff,last_successful_refresh,status FROM metrics.dashboard_data_freshness"
        ).fetchone()
        metric_count = con.execute("SELECT COUNT(*) FROM metrics.metric_catalog").fetchone()[0]
        orphan_count = con.execute(
            "SELECT COALESCE(SUM(orphan_rows),0) FROM audit.orphan_results"
        ).fetchone()[0]
        payroll_gap = con.execute(
            "SELECT MAX(ABS(difference)) FROM audit.payroll_ledger_reconciliation_clean"
        ).fetchone()[0]
        gate, failed = con.execute("SELECT status,critical_checks_failed FROM audit.release_gate").fetchone()
        suppressed = con.execute(
            "SELECT COUNT(*) FROM clean.fact_headcount_monthly WHERE department_id='D00' AND headcount_end<5"
        ).fetchone()[0]

    checks.extend([
        ("Freshness statement", cutoff == date(2026, 9, 30) and refresh is not None,
         f"Cutoff {cutoff}; last refresh {refresh}; status {status}."),
        ("Governed metric layer", metric_count >= 28, f"{metric_count} catalog metrics are available."),
        ("Warehouse relationships", orphan_count == 0, f"{orphan_count} declared orphan rows."),
        ("Payroll reconciliation", abs(float(payroll_gap or 0)) <= 0.01,
         f"Maximum clean payroll-to-ledger gap INR {float(payroll_gap or 0):.8f}."),
        ("Privacy stress case", suppressed > 0,
         f"{suppressed} one-person D00 department-month rows remain excluded from display metrics."),
        ("Raw quality gate is explicit", gate == "REVIEW REQUIRED" and failed > 0,
         f"Gate {gate}; {failed} critical supplied-source findings remain visible."),
    ])

    metadata = list_metrics()
    examples = [get_metric(metric_id, "2026-09", "ALL") for metric_id in API_METRICS]
    api_ok = len(metadata["metrics"]) == 5 and all(
        item.get("metric", {}).get("source_table") and item.get("data_cutoff") and item.get("privacy")
        for item in examples
    )
    checks.append(("Five-metric API contract", api_ok,
                   "M01, M04, M09, M20 and M22 return value, definition, source, freshness and privacy metadata."))

    workflow = (ROOT / ".github" / "workflows" / "monthly-refresh.yml").read_text(encoding="utf-8")
    workflow_ok = all(token in workflow for token in (
        "schedule:", "actions/checkout@v4", "actions/setup-python@v5",
        "actions/upload-artifact@v4", 'python-version: "3.11"',
    ))
    checks.append(("Scheduled refresh definition", workflow_ok,
                   "Monthly cron, manual trigger, Python 3.11 and supported GitHub Action versions are configured."))

    requirements = (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines()
    pinned = bool(requirements) and all("==" in line for line in requirements if line.strip() and not line.startswith("#"))
    checks.append(("Pinned runtime", pinned, f"{len(requirements)} direct dependencies are exactly pinned."))

    build_dir = ROOT / ".artifact_build" / "phase4_verify"
    build_dir.mkdir(parents=True, exist_ok=True)
    pdf = build_pdf(date(2026, 9, 1), build_dir / "PulseIQ_Monthly_Pack_2026-09.pdf")
    xlsx = build_excel(date(2026, 9, 1), build_dir / "PulseIQ_Monthly_Pack_2026-09.xlsx", DB)
    checks.append(("One-command monthly pack", pdf.exists() and xlsx.exists(),
                   f"PDF {pdf.stat().st_size:,} bytes; Excel {xlsx.stat().st_size:,} bytes."))

    pages = ROOT / "pages" / "11_KPI_Builder.py"
    explorer = pages.read_text(encoding="utf-8")
    role_tokens = all(token in explorer for token in ("ADMIN", "HR", "MANAGER", "EXECUTIVE"))
    suppression_tokens = "minimum sample size" in explorer and "HAVING" in explorer
    checks.append(("Role and suppression logic", role_tokens and suppression_tokens,
                   "All four demo roles and minimum-group suppression are present in the explorer."))

    return checks


def write(checks: list[tuple[str, bool, str]]) -> Path:
    lines = [
        "# Phase 4 validation",
        "",
        "Generated by `python scripts/verify_phase4.py`.",
        "",
        "| Check | Result | Evidence |",
        "|---|---|---|",
    ]
    for name, ok, evidence in checks:
        lines.append(f"| {name} | {'PASS' if ok else 'FAIL'} | {evidence} |")
    passed = sum(ok for _, ok, _ in checks)
    lines.extend([
        "",
        f"**Result: {passed}/{len(checks)} Phase 4 validation groups passed.**",
        "",
        "The raw quality gate remains `REVIEW REQUIRED` because the supplied training extract contains planted defects. "
        "This is an expected source finding, while the clean reconciliation, relationship and release checks above pass.",
    ])
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return OUTPUT


if __name__ == "__main__":
    checks = run()
    print(write(checks))
    failed = [name for name, ok, _ in checks if not ok]
    if failed:
        raise SystemExit("Phase 4 checks failed: " + ", ".join(failed))

